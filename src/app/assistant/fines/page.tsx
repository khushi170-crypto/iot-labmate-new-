import { PageHeader } from "@/components/ui/page-header";
import { FinesBoard } from "@/components/fines/fines-board";
import { requireUser } from "@/lib/session";
import { listFines } from "@/lib/fines.service";
import { getCurrency } from "@/lib/settings.service";

export const metadata = { title: "Fines" };

export default async function FinesPage() {
  await requireUser();
  const [fines, currency] = await Promise.all([listFines({ includeRelations: true }), getCurrency()]);

  return (
    <div>
      <PageHeader
        title="Fines"
        description="Collect or waive fines generated by late returns."
      />
      <FinesBoard fines={fines as never} currency={currency} />
    </div>
  );
}